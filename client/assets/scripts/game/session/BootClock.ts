/**
 * 职责：客户端自己可见的那一段启动耗时（B16 §一「首屏可交互」在小游戏运行时里的唯一输入）。
 * 依赖：无 —— 只有 `Date.now()`，刻意不引入引擎符号。
 *
 * <p><b>为什么要有这一份</b>：「首屏可交互 ≤ 3s」今天只有一个读者，
 * {@code tools/verify-perf-runtime.mjs}，而它用的是<b>浏览器自己的墙钟</b>
 * （从 {@code page.goto} 到看见 {@code [boot]} 那行）。那条路在小游戏运行时里不存在 ——
 * 小游戏没有可编程自动化接口（{@code miniprogram-automator} 连上即断），DevTools 里也没有
 * 一个外部时钟能回答"从哪一刻算起"。客户端不把这段时间自己打出来，
 * CC 阶段 6 的「启动耗时的<b>小游戏运行时</b>版本」就不是难量，而是<b>没有输入可量</b>。
 *
 * <p><b>锚点是"本包 JS 第一次被求值"，不是"玩家点开图标"</b>：包体下载、解包、引擎初始化
 * 都发生在我们任何一行代码之前，JS 侧看不见。所以这是一个<b>下界</b>而不是玩家体感全量。
 * 写成下界而不是假装成体感，是因为这条数一旦被当成"首屏已达标"的证据，
 * 被漏掉的那一段（低端安卓上往往正是最大的一段）就再也没有人去量它了。
 *
 * <p><b>为什么不用 {@code performance.now()} 或 {@code sys.now()}</b>：
 * ① 锚点模块必须能被无引擎单测跑，而引入 {@code cc} 就等于把锚点绑到组件生命周期上
 * —— 那比"模块求值"晚，会让读数凭空少算一段并且每次都少得不一样多；
 * ② {@code performance} 在小游戏运行时是适配层提供的，各版本行为不一致，
 * 这段计时宁可粗也不要依赖一个我们没有核对过的接口。
 * 代价是墙钟会被玩家改、也会被系统 NTP 校正，所以下面把读数夹在 0 之上。
 */

/** 锚点：本模块被求值的那一刻（= 客户端自己的代码开始跑起来的最早可见时刻）。 */
const BOOT_EPOCH_MS = Date.now()

/**
 * 从锚点到 {@code now} 的毫秒数。
 *
 * <p>时钟被往回调时读作 <b>0 而不是负数</b>：负数经 JSON 出去会被读成一个荒谬的小值，
 * 而「启动只用了 0ms」恰恰是最不该出现的那盏绿灯 —— 它看起来像达标，实际是测量本身坏了。
 *
 * @param now 结束时刻，默认取当前时间；参数化是为了让"时钟倒拨"这一条可以被单测证伪
 */
export function bootElapsedMs(now: number = Date.now()): number {
  return Math.max(0, now - BOOT_EPOCH_MS)
}
