package com.ironoath.core.reward;

import java.util.List;

/**
 * 职责：通用奖励发放器端口 —— 任务/活动/战斗/邮件/补偿全部走这里（B04 §5，本批次核心）。
 * 依赖：无（纯接口）。
 *
 * <p><b>实现铁律</b>（B04 禁止项）：实现内部必须调用资源模块与背包模块的接口，
 * <b>不允许直接操作数据库</b>。绕过它们就等于绕过上限校验、事件通知与战力重算，
 * 结果是「资源加上了但顶部资源条没刷新」「道具进库了但战力没变」这类数据不一致，
 * 而且每一处绕过都是一条独立的、需要单独排查的路径。
 *
 * <p>失败处理：绝不静默吞异常。任何一条奖励发放失败都必须落日志并进补偿队列，
 * 由 {@link GrantResult#compensationId()} 返回可查凭证。
 * 静默失败是最坏的结果 —— 玩家没拿到东西，而系统里没有任何痕迹。
 */
public interface RewardService {

    /**
     * 发放一批奖励。
     *
     * <p>语义是<b>尽力发放</b>而不是全有或全无：一条奖励溢出（背包满）不应该让
     * 同一批里的其它奖励也失败。溢出部分转邮件补发，出错部分进补偿队列。
     * 这与「扣资源」的语义相反 —— 扣减必须原子（要么全扣要么不扣），
     * 发放则应该尽量让玩家拿到能拿的部分。
     *
     * @param playerId 目标玩家
     * @param rewards  奖励列表，顺序即客户端飘字播放顺序（B04 §6：不可同时堆叠）
     * @param ctx      来源与溢出策略
     * @return 发放结果，含实际发放、溢出、补偿记录三部分
     */
    GrantResult grant(String playerId, List<RewardItem> rewards, RewardContext ctx);
}
