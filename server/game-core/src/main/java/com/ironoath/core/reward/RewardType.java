package com.ironoath.core.reward;

/**
 * 职责：奖励类型枚举 —— 通用发放器按它分派到对应的子系统。
 * 依赖：无（纯 Java）。
 *
 * <p>为什么要有这个枚举而不是让每个系统自己发奖：任务、活动、战斗、邮件、补偿
 * 五个系统都要发「资源 + 道具 + 武将碎片」的混合奖励。各自实现就会各自漏掉
 * 上限校验、事件通知、溢出转邮件中的某一项，而且五份代码的行为会慢慢分叉。
 * 统一走发放器之后，「发奖」这件事只有一处实现（B04 §5）。
 */
public enum RewardType {

    /** 资源（WOOD/STONE/IRON/GRAIN/GOLD），id 为 resource 表的行 id。 */
    RESOURCE,

    /** 道具，id 为 item 表的行 id。进背包，受堆叠上限与背包容量约束。 */
    ITEM,

    /**
     * 武将碎片，<b>id 为 hero 表的行 id</b>（不是稀有度）。发放时按该武将的稀有度落到
     * {@code item_mat_hero_frag_<稀有度小写>}，见 {@code HeroFragmentExtras#fragmentItemOf}；
     * 现有调用方 {@code GachaAppService} 传的就是 {@code draw.heroId()}。
     * 凑满合成武将（B06 §碎片合成）。这句写错会把外键校验指向另一张表。
     */
    HERO_FRAGMENT,

    /**
     * 整卡武将，<b>id 为 hero 表的行 id</b>。与 {@link #HERO_FRAGMENT} 的区别是「直接获得这名武将」
     * 而不是给碎片 —— 所以它只用于**确定的赠送**（B06 §1「主线赠送：首日必得 1 名 SR」），
     * 抽卡那条不确定性路径仍旧走碎片（重复武将转碎片的经济也在那一侧）。
     *
     * <p><b>为什么必须与碎片分开而不是复用 HERO_FRAGMENT</b>：两者下游完全不同 ——
     * 碎片进背包（可堆叠、受容量约束、可攒可交易），整卡进武将册（唯一、不可堆叠、立刻可上阵）。
     * 复用会让「发 50 个碎片」与「直接给这名武将」变成同一个调用，而调用方少写一个 0
     * 就从「送一名武将」变成「送 50 个碎片」，且两者都不会报错。
     */
    HERO,

    /** 体力，id 固定为 STAMINA。打野与关卡的消耗闸门。 */
    STAMINA,

    /**
     * 建造队列扩容等一次性特权，id 为特权标识。
     *
     * <p>与 ITEM 的区别：特权改变的是玩家账户的长期能力（队列数 +1），
     * 不是背包里可堆叠可交易的东西。混在一起会让「用了就没了」和「永久生效」
     * 两种语义共用一条代码路径，迟早出错。
     */
    PRIVILEGE
}
