package com.ironoath.web.reward;

/**
 * 职责：为一切「结果必须不可被客户端挑选」的随机业务提供种子（开箱、抽卡）。
 * 依赖：无。
 *
 * <p><b>为什么要单独抽一个接口</b>：种子的来源决定了开箱结果谁能影响。
 * B04 禁止项写得很直接 —— 不要在客户端本地开箱，结果由服务端下发。
 * 这句话的真正含义不是「计算发生在服务端」，而是「<b>客户端无法挑选结果</b>」。
 * 如果种子由 requestId、客户端时间或任何请求字段推导出来，客户端就能离线枚举出
 * 哪个 requestId 会开出好东西，再拿那个 requestId 发请求 —— 计算确实在服务端，
 * 但结果已经被玩家挑过了。所以种子必须来自客户端完全无法预测、也无法重放的熵源。
 *
 * <p>抽成接口而不是直接 {@code new SecureRandom()} 有两个理由：
 * 单测需要确定性种子（验收 4「同 seed 两次结果完全一致」要能端到端复现），
 * 以及未来若改为「服务端持久化的开箱序号」也不需要改调用方。
 *
 * <p>种子会随响应下发并写进日志：这不是泄密，而是可复现性的必要条件 ——
 * 客服接到「我开了 100 个什么都没出」「我抽了 80 抽没保底」的申诉时，
 * 用 (seed, count) 重跑 {@code ChestOpener.openBatch} / {@code GachaEngine.draw}
 * 就能逐条还原当时的结果。种子只对「已经发生的那一次」有意义，对下一次毫无预测价值。
 *
 * <p>抽卡与开箱共用一个种子源是刻意的：两者对种子的要求完全相同
 * （服务端生成、客户端无法预测、事后凭 seed 可复现），
 * 分成两个接口只会让「哪一个才是安全的那个」变成需要读代码才能回答的问题。
 */
public interface ServerSeedSource {

    /** 取一个客户端无法预测的种子。 */
    long nextSeed();
}
