package com.ironoath.web.config;

/**
 * 职责：服务端「现在几点」的**可覆盖口**（只在 dev profile 有一个实现，见 {@link DevClockSpeed}）。
 * 依赖：无框架类型。
 *
 * <p><b>为什么需要它</b>：国策一轮 48 小时（24h 投票窗 + 24h 生效段，B13 §4）、赛季与周税同理。
 * 探针与真机截图都等不到，于是「投票段 / 生效段长什么样」只能靠拨钟的单元测试 ——
 * 而「文本断言全绿而画面是坏的」在本仓已经发生过不止一次（候选区的键压住文字、
 * 倒计时写成「距开票 23 小时前」，两次都是文本断言全绿）。
 *
 * <p><b>为什么是「倍速」而不是「偏移」</b>：
 * <ul>
 *   <li><b>偏移</b>要一个运行期可改的入口（端点或文件）—— 前者碰「不许有跳门槛的端点」那条红线，
 *       后者让 dev 下时间有两个来源（「同一个数字两个家」那一族）。</li>
 *   <li><b>倍速</b>的入口只有启动时那一个环境变量，之后不可改 ——
 *       那是「模式隔离」纪律要的形状：不设就与改动前逐位一致。</li>
 * </ul>
 *
 * <p><b>为什么不直接改 {@code GameBeansConfig} 里那个 TimeService bean</b>：
 * 那个 bean 在**所有** profile 里都有（prod 也在），在里面读环境变量就变成
 * 「prod 读得到、只是恰好没设」—— 与 {@link NewPlayerBoost} 那族相比差了一层结构保证。
 */
public interface ClockSource {

    /**
     * 「没设」= 真实系统时间。**默认实现就是没设** ——
     * 它是接口常量而不是抽象方法刻意如此：没装配任何覆盖的上下文（单测、prod）
     * 拿到的是一个安全的空实现，不必在每个测试里塞一个 mock。
     */
    ClockSource SYSTEM = () -> System.currentTimeMillis();

    /** 现在几点（服务端时间戳，毫秒）。 */
    long nowMillis();

    /** 当前倍速（1 = 真实时间）。给日志与探针自查用。 */
    default long speed() {
        return 1L;
    }
}