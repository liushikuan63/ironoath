package com.ironoath.battle;

/**
 * 职责：阵型类型。
 * 依赖：无。
 *
 * <p><b>V1 只有 STANDARD 一种</b>（B05 开放问题 3 的决定：建议 V1 不做玩家可选阵型）。
 * 保留这个字段是为了：
 * <ol>
 *   <li>三排损失分摊（前 0.5 / 中 0.3 / 后 0.2）是 B00 结算公式的一部分，必须有「兵种在哪一排」
 *       的映射，这个映射就是阵型</li>
 *   <li>后续要加阵型时不必改 BattleInput 的契约形状（改协议比加协议贵得多）</li>
 * </ol>
 *
 * <p>注意区分两件事：三排分摊是<b>固定规则</b>（V1 就有），玩家可选阵型是<b>玩法系统</b>（V1 不做）。
 */
public enum FormationType {
    /**
     * 标准阵型：重步兵前排、轻骑兵中排、弓兵与攻城器后排。
     *
     * <p>依据是兵种的承伤定位：步兵高防高血适合扛线（承担 50% 损失），
     * 骑兵靠机动不适合站桩（30%），弓兵与攻城器是脆皮输出必须被挡在后面（20%）。
     * 这个映射让「阵型」在 V1 就产生真实策略后果 —— 全出弓兵会被步兵冲到脸上打崩。
     */
    STANDARD
}
