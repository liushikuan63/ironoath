package com.ironoath.battle;

/**
 * 职责：技能效果类型。
 * 依赖：无。
 *
 * <p>取值与 contract/config/skill.json 的 effect 字段一一对应。
 * 每个效果都作用在<b>独立的乘区</b>上，绝不合并成「总加成」—— 否则调数值时无法定位
 * 是哪个系统出了问题（B05 §1.3 乘区隔离）。
 */
public enum SkillEffect {
    /** 对敌方造成额外伤害，value 是相对己方有效攻击的倍率。 */
    DAMAGE,
    /** 按己方已损失兵力的比例回复，value 是回复比例。 */
    HEAL,
    /** 提升己方攻击乘区，value 是百分比。 */
    BUFF_ATK,
    /** 提升己方防御乘区，value 是百分比。 */
    BUFF_DEF,
    /** 削减敌方攻击乘区，value 是百分比。 */
    DEBUFF_ATK,
    /** 削减敌方防御乘区，value 是百分比。 */
    DEBUFF_DEF,
    /**
     * 跳过敌方一次攻击结算。
     *
     * <p>目前没有任何技能使用它 —— 硬控会让被控方玩家完全失去参与感（他什么也没做就输了），
     * 这与 C00 公理二「被打是社交的起点」冲突：被硬控的人不会想叫人反打，只会想退游。
     * 保留枚举值是为了让「我们评估过并否决了硬控」这件事在代码里有痕迹。
     */
    SKIP_TURN
}
